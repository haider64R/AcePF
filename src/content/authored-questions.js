import { earliestCoreScope } from "./scopes.js";

// Original AcePF practice. These are not historical FAST questions. The
// assessment-style tag denotes reasoning density only, never provenance.
function base(id, title, type, question, topics, difficulty, extra = {}) {
  const { assessmentStyle = false, ...fields } = extra;
  return {
    id: `ace-${id}`,
    title,
    type,
    question,
    topics,
    primaryTopic: topics[0],
    scopeId: earliestCoreScope(topics),
    difficulty,
    source: { type: "authored", name: "AcePF original practice" },
    status: "verified",
    tags: [assessmentStyle ? "assessment-style" : "learning-practice"],
    ...fields,
  };
}
const out = (
  id,
  title,
  question,
  code,
  answer,
  explanation,
  topics,
  difficulty = "medium",
  assessmentStyle = false,
) =>
  base(id, title, "predict-output", question, topics, difficulty, {
    code,
    answer,
    explanation,
    autoGradable: true,
    visualizer: { compatible: true },
    verification: "execution-verified",
    assessmentStyle,
  });
const choice = (
  id,
  title,
  question,
  options,
  answer,
  explanation,
  topics,
  difficulty = "easy",
  assessmentStyle = false,
) =>
  base(id, title, "multiple-choice", question, topics, difficulty, {
    options: options.map((text, i) => ({
      id: String.fromCharCode(97 + i),
      text,
    })),
    answer,
    explanation,
    autoGradable: true,
    visualizer: { compatible: false },
    verification: "answer-reviewed",
    assessmentStyle,
  });
const written = (
  id,
  title,
  question,
  answer,
  explanation,
  topics,
  difficulty = "medium",
) =>
  base(id, title, "code-writing", question, topics, difficulty, {
    answer,
    explanation,
    autoGradable: false,
    visualizer: { compatible: false },
    verification: "answer-reviewed",
  });

